'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {verifyHmac,extractUsername,validatePayload}=require('../lib/sepay-verification');
const now=1762420000;
const secret='sample-secret-for-testing-only-no-real-token';
const raw=Buffer.from('{"id":92704,"accountNumber":"123456789","transferAmount":10000,"transferType":"in","content":"NAP kitphangiatu"}');
const timestamp=String(now);
const signature='sha256='+crypto.createHmac('sha256',secret).update(timestamp+'.').update(raw).digest('hex');
assert.equal(verifyHmac({raw,secret,signature,timestamp,nowSeconds:now}).ok,true);
assert.equal(verifyHmac({raw:Buffer.from(raw.toString().replace('10000','99999')),secret,signature,timestamp,nowSeconds:now}).ok,false);
assert.equal(verifyHmac({raw,secret,signature,timestamp,nowSeconds:now+301}).ok,false);
assert.equal(verifyHmac({raw,secret,signature:'sha256='+'0'.repeat(64),timestamp,nowSeconds:now}).ok,false);
assert.equal(extractUsername('abc NAP kitphangiatu XYZ'),'kitphangiatu');
assert.equal(extractUsername('NAP foo NAP bar'),null);
assert.equal(validatePayload(JSON.parse(raw.toString()),'123456789').ok,true);
assert.equal(validatePayload({...JSON.parse(raw.toString()),transferType:'out'},'123456789').ok,false);
assert.equal(validatePayload({...JSON.parse(raw.toString()),accountNumber:'987654321'},'123456789').ok,false);
assert.equal(validatePayload({...JSON.parse(raw.toString()),transferAmount:1.5},'123456789').ok,false);
console.log('9 security checks passed.');
