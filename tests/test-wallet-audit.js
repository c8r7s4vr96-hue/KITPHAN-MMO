'use strict';
const assert=require('node:assert/strict');
const {summarize,goodAmount,listForUsername,normalize}=require('../lib/wallet-audit');
let t=0;
const check=(fn)=>{fn();t++};
check(()=>assert.equal(goodAmount(10000),10000));
check(()=>assert.equal(goodAmount('010000'),10000));
check(()=>assert.equal(goodAmount(-1),null));
check(()=>assert.equal(goodAmount(0.1),null));
check(()=>assert.equal(goodAmount('10.000'),null));
check(()=>assert.equal(normalize('Thành công'),'thanh cong'));
check(()=>assert.equal(listForUsername([{user:'a'},{user:'b'}],'a').length,1));
const sample={username:'kitphangiatu',user:{balance:99000000,totalDeposited:100050000},depositRaw:{d1:{user:'kitphangiatu',status:'Thành công',amount:100000},d2:{user:'kitphangiatu',status:'Thành công',amount:50000,transactionId:'123'},d3:{user:'kitphangiatu',status:'Thành công',amount:50000,transactionId:'123'},d4:{user:'kitphangiatu',status:'Chờ xử lý',amount:20000}},orderRaw:{o1:{user:'kitphangiatu',status:'Hoàn thành',total:12000},o2:{user:'kitphangiatu',status:'Đang xử lý',total:5000}},premiumRaw:{p1:{status:'needs_review'}},eventsRaw:{p1:{provider:'sepay',status:'pending_reconciliation',credited:false,usernameHint:'kitphangiatu'},p2:{provider:'sepay',usernameHint:'other'}}};
const s=summarize(sample.username,sample.user,sample.depositRaw,sample.orderRaw,sample.premiumRaw,sample.eventsRaw);
check(()=>assert.equal(s.recordedDeposits.count,3));
check(()=>assert.equal(s.recordedDeposits.amountVnd,200000));
check(()=>assert.equal(s.recordedDeposits.withoutBankId,1));
check(()=>assert.equal(s.recordedDeposits.duplicates,1));
check(()=>assert.equal(s.legacyOrders.completedTotalVnd,12000));
check(()=>assert.equal(s.legacyOrders.processingCount,1));
check(()=>assert.equal(s.premiumOrders.needReview,1));
check(()=>assert.equal(s.paymentEvents.pendingCount,1));
check(()=>assert.equal(s.spendableBalanceVnd,null));
check(()=>assert.equal(s.walletLocked,true));
check(()=>assert.equal(s.scan.bankVerified,false));
check(()=>assert.throws(()=>summarize('bad/path',{}, {},{}, {},{})));
console.log(t+' read-only wallet audit assertions passed');
