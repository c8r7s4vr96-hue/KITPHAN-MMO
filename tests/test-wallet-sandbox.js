'use strict';
const assert=require('node:assert/strict');
const {makeCode,extractTestCode,applySandboxCredit,alreadyApplied}=require('../lib/wallet-sandbox');
let count=0;
const test=(name,fn)=>{fn();count++;};
const uid='9UZ3fvz2yeawGr964zKvS9qfANh2';
const code=makeCode();
test('strong random code',()=>assert.match(code,/^KPTEST[A-F0-9]{16}$/));
test('parser accepts a single code',()=>assert.equal(extractTestCode('memo NAP '+code+' abc'),code));
test('parser rejects ambiguous codes',()=>assert.equal(extractTestCode('NAP '+code+' and NAP '+code),null));
test('parser ignores usernames from old system',()=>assert.equal(extractTestCode('NAP adminkit'),null));
let a=applySandboxCredit(null,{uid,txId:1234,intentId:'aaaaaaaaaaaaaaaaaaaa',amountVnd:10000,now:1});
test('sandbox ledger and wallet sum atomic',()=>{assert.equal(a.availableVnd,10000);assert.equal(a.ledger.sepay_1234.deltaVnd,10000);assert.equal(a.kind,'simulation_only');});
test('duplicate tx cannot credit',()=>assert.equal(applySandboxCredit(a,{uid,txId:1234,intentId:'aaaaaaaaaaaaaaaaaaaa',amountVnd:10000,now:2}),undefined));
test('different tx cannot reuse same intent',()=>assert.equal(applySandboxCredit(a,{uid,txId:1235,intentId:'aaaaaaaaaaaaaaaaaaaa',amountVnd:10000,now:2}),undefined));
test('processed marker verifies settled intent',()=>assert.equal(alreadyApplied(a,1234,'aaaaaaaaaaaaaaaaaaaa'),true));
test('invalid or non-integer amount rejected',()=>assert.equal(applySandboxCredit(null,{uid,txId:1234,intentId:'aaaaaaaaaaaaaaaaaaaa',amountVnd:10000.3,now:1}),undefined));
test('amount cap rejected',()=>assert.equal(applySandboxCredit(null,{uid,txId:1234,intentId:'aaaaaaaaaaaaaaaaaaaa',amountVnd:999999999,now:1}),undefined));
for(let i=1;i<=100;i++){const next=applySandboxCredit(a,{uid,txId:2000+i,intentId:i.toString(36).padStart(20,'0'),amountVnd:10000,now:20+i});if(next)a=next;}
test('sandbox balance never exceeds a million',()=>assert.equal(a.availableVnd,1000000));
test('max event cap blocks more',()=>assert.equal(applySandboxCredit(a,{uid,txId:50000,intentId:'cccccccccccccccccccc',amountVnd:10000,now:300}),undefined));
console.log(count+' pure sandbox assertions passed');
